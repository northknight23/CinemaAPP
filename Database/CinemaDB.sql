CREATE DATABASE CINEMADB;
USE CINEMADB;
CREATE TABLE MOVIE(
MovieID INT IDENTITY(1,1) PRIMARY KEY,
Title NVARCHAR(200) NOT NULL,
DurationMin INT NOT NULL,
Genre NVARCHAR(50),
Agerating NVARCHAR(30),
MovieStatus NVARCHAR(30),
ReleaseDate date,
PosterPath NVARCHAR(260),
MovieDescription NVARCHAR(1000)
);

CREATE TABLE ROOM(
RoomID INT IDENTITY(1,1) PRIMARY KEY,
RoomName NVARCHAR(50) NOT NULL,
RoomType NVARCHAR(10),
NumRows int NOT NULL,
SeatsPerRow int NOT NULL
)

CREATE TABLE ACCOUNT(
AccountID INT IDENTITY(1,1) PRIMARY KEY,
Username NVARCHAR(50) NOT NULL,
PasswordHash NVARCHAR(256) NOT NULL,
FullName NVARCHAR(50) NOT NULL,
AccountRole NVARCHAR(20)
);

CREATE TABLE SHOWTIME(
ShowtimeID INT IDENTITY(1,1) PRIMARY KEY,
MovieID INT NOT NULL,
RoomID INT NOT NULL,
StartTime datetime2 NOT NULL,
ShowFormat NVARCHAR(10),
AudioType NVARCHAR(20),
BasePrice MONEY NOT NULL,
CONSTRAINT FK_SHOWTIME_MOVIE FOREIGN KEY (MovieID) REFERENCES MOVIE(MovieID),
CONSTRAINT FK_SHOWTIME_ROOM  FOREIGN KEY (RoomID)  REFERENCES ROOM(RoomID)
);

CREATE TABLE SEAT(
SeatID INT IDENTITY(1,1) PRIMARY KEY,
RoomID INT NOT NULL,
RowLabel NVARCHAR(5) NOT NULL,
SeatNumber INT NOT NULL,
CONSTRAINT FK_SEAT_ROOM FOREIGN KEY (RoomID) REFERENCES ROOM(RoomID)
);

CREATE TABLE BOOKING(
BookingID INT IDENTITY(1,1) PRIMARY KEY,
AccountID INT NOT NULL,
CreatedAt DATETIME2,
TotalAmount MONEY NOT NULL,
BookingStatus NVARCHAR(20),
CONSTRAINT FK_BOOKING_ACCOUNT FOREIGN KEY(AccountID) REFERENCES ACCOUNT(AccountID)
);

CREATE TABLE TICKET(
TicketID INT IDENTITY(1,1) PRIMARY KEY,
BookingID INT NOT NULL,
ShowtimeID INT NOT NULL,
SeatID INT NOT NULL,
Price MONEY,
CONSTRAINT FK_TICKET_BOOKING FOREIGN KEY (BookingID) REFERENCES BOOKING(BookingID),
CONSTRAINT FK_TICKET_SHOWTIME FOREIGN KEY (ShowtimeID) REFERENCES SHOWTIME(ShowtimeID),
CONSTRAINT FK_TICKET_SEAT FOREIGN KEY (SeatID) REFERENCES SEAT(SeatID)
);

ALTER TABLE ACCOUNT ADD CONSTRAINT UQ_ACCOUNT UNIQUE(Username);
ALTER TABLE SEAT ADD CONSTRAINT UQ_SEAT UNIQUE(RoomID, RowLabel, SeatNumber);
ALTER TABLE ROOM ADD CONSTRAINT UQ_ROOM UNIQUE(RoomName);
ALTER TABLE SHOWTIME ADD CONSTRAINT CK_SHOWTIME CHECK(BasePrice >= 0);
ALTER TABLE TICKET ADD CONSTRAINT CK_TICKET CHECK(Price >= 0);
ALTER TABLE BOOKING ADD CONSTRAINT DF_BOOKING_CREATEDAT DEFAULT SYSDATETIME() FOR CreatedAt;
ALTER TABLE TICKET ADD CONSTRAINT UQ_TICKET_SEAT UNIQUE (ShowtimeID, SeatID);