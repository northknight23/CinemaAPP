CREATE DATABASE CINEMADB;
USE CINEMADB;
CREATE TABLE MOVIE(
MovieID INT IDENTITY(1,1) PRIMARY KEY,
Title NVARCHAR(200) NOT NULL,
DurationMin INT NOT NULL,
Genre NVARCHAR(50),
Agerating NVARCHAR(30),
MovieStatus NVARCHAR(30),
ReleaseDate date,
PosterPath NVARCHAR(260),
MovieDescription NVARCHAR(1000)
);

CREATE TABLE ROOM(
RoomID INT IDENTITY(1,1) PRIMARY KEY,
RoomName NVARCHAR(50) NOT NULL,
RoomType NVARCHAR(10),
NumRows int NOT NULL,
SeatsPerRow int NOT NULL
);

CREATE TABLE ACCOUNT(
AccountID INT IDENTITY(1,1) PRIMARY KEY,
Username NVARCHAR(50) NOT NULL,
PasswordHash NVARCHAR(256) NOT NULL,
FullName NVARCHAR(50) NOT NULL,
AccountRole NVARCHAR(20) NOT NULL,
IsActive BIT NOT NULL
);

CREATE TABLE SHOWTIME(
ShowtimeID INT IDENTITY(1,1) PRIMARY KEY,
MovieID INT NOT NULL,
RoomID INT NOT NULL,
StartTime datetime2 NOT NULL,
ShowFormat NVARCHAR(10),
AudioType NVARCHAR(20),
BasePrice MONEY NOT NULL,
CONSTRAINT FK_SHOWTIME_MOVIE FOREIGN KEY (MovieID) REFERENCES MOVIE(MovieID),
CONSTRAINT FK_SHOWTIME_ROOM  FOREIGN KEY (RoomID)  REFERENCES ROOM(RoomID),
CONSTRAINT UQ_SHOWTIME_ROOM UNIQUE (ShowtimeID, RoomID)
);

CREATE TABLE SEAT(
SeatID INT IDENTITY(1,1) PRIMARY KEY,
RoomID INT NOT NULL,
RowLabel NVARCHAR(5) NOT NULL,
SeatNumber INT NOT NULL,
SeatType NVARCHAR(10) NOT NULL,
CONSTRAINT FK_SEAT_ROOM FOREIGN KEY (RoomID) REFERENCES ROOM(RoomID),
CONSTRAINT UQ_SEAT_ROOM UNIQUE (SeatID, RoomID)
);

CREATE TABLE CUSTOMER(
CustomerID INT IDENTITY(1,1) PRIMARY KEY,
FullName   NVARCHAR(100) NOT NULL,
Phone      NVARCHAR(15)  NOT NULL,
Points     INT NOT NULL DEFAULT 0,
CONSTRAINT UQ_CUSTOMER_Phone UNIQUE (Phone)
);

CREATE TABLE BOOKING(
BookingID INT IDENTITY(1,1) PRIMARY KEY,
AccountID INT NOT NULL,
CustomerID INT,
CreatedAt DATETIME2 NOT NULL,
TotalAmount MONEY NOT NULL,
BookingStatus NVARCHAR(20) NOT NULL,
PaymentMethod NVARCHAR(20),
CashGiven MONEY,
PointsEarned INT NOT NULL,
PointsUsed INT NOT NULL,
CancelReason NVARCHAR(200),
CancelledAt DATETIME2,
CancelledBy INT,
CONSTRAINT FK_BOOKING_ACCOUNT FOREIGN KEY(AccountID) REFERENCES ACCOUNT(AccountID),
CONSTRAINT FK_BOOKING_CUSTOMER FOREIGN KEY(CustomerID) REFERENCES CUSTOMER(CustomerID),
CONSTRAINT FK_BOOKING_CANCELLEDBY FOREIGN KEY(CancelledBy) REFERENCES ACCOUNT(AccountID)
);

CREATE TABLE TICKET(
TicketID INT IDENTITY(1,1) PRIMARY KEY,
BookingID INT NOT NULL,
ShowtimeID INT NOT NULL,
RoomID INT NOT NULL,
SeatID INT NOT NULL,
Price MONEY NOT NULL,
TicketStatus NVARCHAR(20) NOT NULL,
CONSTRAINT FK_TICKET_BOOKING FOREIGN KEY (BookingID) REFERENCES BOOKING(BookingID),
CONSTRAINT FK_TICKET_SHOWTIME FOREIGN KEY (ShowtimeID, RoomID) REFERENCES SHOWTIME(ShowtimeID, RoomID),
CONSTRAINT FK_TICKET_SEAT FOREIGN KEY (SeatID, RoomID) REFERENCES SEAT(SeatID, RoomID)
);

ALTER TABLE ACCOUNT ADD CONSTRAINT UQ_ACCOUNT UNIQUE(Username);
ALTER TABLE SEAT ADD CONSTRAINT UQ_SEAT UNIQUE(RoomID, RowLabel, SeatNumber);
ALTER TABLE ROOM ADD CONSTRAINT UQ_ROOM UNIQUE(RoomName);
ALTER TABLE SHOWTIME ADD CONSTRAINT CK_SHOWTIME CHECK(BasePrice >= 0);
ALTER TABLE TICKET ADD CONSTRAINT CK_TICKET CHECK(Price >= 0);
ALTER TABLE BOOKING ADD CONSTRAINT DF_BOOKING_CREATEDAT DEFAULT SYSDATETIME() FOR CreatedAt;

ALTER TABLE MOVIE ADD CONSTRAINT CK_MOVIE_DURATION CHECK(DurationMin > 0);
ALTER TABLE MOVIE ADD CONSTRAINT CK_MOVIE_AGERATING CHECK(Agerating IN (N'P', N'K', N'T13', N'T16', N'T18', N'C'));
ALTER TABLE MOVIE ADD CONSTRAINT CK_MOVIE_STATUS CHECK(MovieStatus IN (N'Đang chiếu', N'Sắp chiếu', N'Ngừng chiếu'));

ALTER TABLE ROOM ADD CONSTRAINT CK_ROOM_SIZE CHECK(NumRows > 0 AND SeatsPerRow > 0);
ALTER TABLE ROOM ADD CONSTRAINT CK_ROOM_TYPE CHECK(RoomType IN (N'2D', N'3D', N'IMAX'));

ALTER TABLE ACCOUNT ADD CONSTRAINT CK_ACCOUNT_ROLE CHECK(AccountRole IN (N'Admin', N'Staff'));
ALTER TABLE ACCOUNT ADD CONSTRAINT DF_ACCOUNT_ROLE DEFAULT N'Staff' FOR AccountRole;
ALTER TABLE ACCOUNT ADD CONSTRAINT DF_ACCOUNT_ISACTIVE DEFAULT 1 FOR IsActive;

ALTER TABLE SHOWTIME ADD CONSTRAINT CK_SHOWTIME_FORMAT CHECK(ShowFormat IN (N'2D', N'3D', N'IMAX'));
ALTER TABLE SHOWTIME ADD CONSTRAINT CK_SHOWTIME_AUDIO CHECK(AudioType IN (N'Phụ đề', N'Lồng tiếng'));

ALTER TABLE SEAT ADD CONSTRAINT CK_SEAT_NUMBER CHECK(SeatNumber > 0);
ALTER TABLE SEAT ADD CONSTRAINT CK_SEAT_TYPE CHECK(SeatType IN (N'Standard', N'Vip', N'Couple'));
ALTER TABLE SEAT ADD CONSTRAINT DF_SEAT_TYPE DEFAULT N'Standard' FOR SeatType;

ALTER TABLE CUSTOMER ADD CONSTRAINT CK_CUSTOMER_POINTS CHECK(Points >= 0);

ALTER TABLE BOOKING ADD CONSTRAINT CK_BOOKING_TOTAL CHECK(TotalAmount >= 0);
ALTER TABLE BOOKING ADD CONSTRAINT CK_BOOKING_STATUS CHECK(BookingStatus IN (N'Paid', N'Cancelled'));
ALTER TABLE BOOKING ADD CONSTRAINT DF_BOOKING_STATUS DEFAULT N'Paid' FOR BookingStatus;
ALTER TABLE BOOKING ADD CONSTRAINT CK_BOOKING_PAYMENT CHECK(PaymentMethod IN (N'Cash', N'Transfer', N'Card'));
ALTER TABLE BOOKING ADD CONSTRAINT CK_BOOKING_CASH CHECK(CashGiven IS NULL OR (PaymentMethod = N'Cash' AND CashGiven >= TotalAmount));
ALTER TABLE BOOKING ADD CONSTRAINT CK_BOOKING_POINTS CHECK(PointsEarned >= 0);
ALTER TABLE BOOKING ADD CONSTRAINT DF_BOOKING_POINTS DEFAULT 0 FOR PointsEarned;
ALTER TABLE BOOKING ADD CONSTRAINT CK_BOOKING_POINTS_USED CHECK(PointsUsed >= 0);
ALTER TABLE BOOKING ADD CONSTRAINT DF_BOOKING_POINTS_USED DEFAULT 0 FOR PointsUsed;
ALTER TABLE BOOKING ADD CONSTRAINT CK_BOOKING_GUEST_POINTS CHECK(CustomerID IS NOT NULL OR (PointsEarned = 0 AND PointsUsed = 0));
ALTER TABLE BOOKING ADD CONSTRAINT CK_BOOKING_CANCEL CHECK(BookingStatus <> N'Cancelled' OR (CancelledAt IS NOT NULL AND CancelledBy IS NOT NULL));

ALTER TABLE TICKET ADD CONSTRAINT CK_TICKET_STATUS CHECK(TicketStatus IN (N'Active', N'Cancelled'));
ALTER TABLE TICKET ADD CONSTRAINT DF_TICKET_STATUS DEFAULT N'Active' FOR TicketStatus;
CREATE UNIQUE INDEX UQ_TICKET_SEAT ON TICKET(ShowtimeID, SeatID) WHERE TicketStatus = N'Active';

CREATE INDEX IX_SHOWTIME_START ON SHOWTIME(StartTime);
CREATE INDEX IX_SHOWTIME_ROOM_START ON SHOWTIME(RoomID, StartTime);
CREATE INDEX IX_TICKET_BOOKING ON TICKET(BookingID);
CREATE INDEX IX_BOOKING_CREATEDAT ON BOOKING(CreatedAt) INCLUDE (BookingStatus, TotalAmount);
CREATE INDEX IX_BOOKING_ACCOUNT ON BOOKING(AccountID);
CREATE INDEX IX_BOOKING_CUSTOMER ON BOOKING(CustomerID);

CREATE TABLE SHIFT_HANDOVER(
ShiftHandoverID INT IDENTITY(1,1) PRIMARY KEY,
ShiftDate       DATE NOT NULL,
AccountID       INT NOT NULL,
ReportedCash    MONEY NULL,
ReportNote      NVARCHAR(300) NULL,
ReportedAt      DATETIME2 NULL,
ConfirmedCash   MONEY NULL,
ConfirmNote     NVARCHAR(300) NULL,
ConfirmedAt     DATETIME2 NULL,
ConfirmedBy     INT NULL,
CONSTRAINT UQ_SHIFT_HANDOVER_DATE_ACCOUNT UNIQUE (ShiftDate, AccountID),
CONSTRAINT FK_SHIFT_HANDOVER_ACCOUNT FOREIGN KEY (AccountID) REFERENCES ACCOUNT(AccountID),
CONSTRAINT FK_SHIFT_HANDOVER_CONFIRMEDBY FOREIGN KEY (ConfirmedBy) REFERENCES ACCOUNT(AccountID),
CONSTRAINT CK_SHIFT_HANDOVER_REPORTED_CASH CHECK (ReportedCash IS NULL OR ReportedCash >= 0),
CONSTRAINT CK_SHIFT_HANDOVER_CONFIRMED_CASH CHECK (ConfirmedCash IS NULL OR ConfirmedCash >= 0),
CONSTRAINT CK_SHIFT_HANDOVER_STATE CHECK (ReportedAt IS NOT NULL OR ConfirmedAt IS NOT NULL),
CONSTRAINT CK_SHIFT_HANDOVER_REPORT_PAIR CHECK ((ReportedAt IS NULL AND ReportedCash IS NULL) OR (ReportedAt IS NOT NULL AND ReportedCash IS NOT NULL)),
CONSTRAINT CK_SHIFT_HANDOVER_CONFIRM_PAIR CHECK ((ConfirmedAt IS NULL AND ConfirmedCash IS NULL AND ConfirmedBy IS NULL) OR (ConfirmedAt IS NOT NULL AND ConfirmedCash IS NOT NULL AND ConfirmedBy IS NOT NULL))
);
CREATE INDEX IX_SHIFT_HANDOVER_DATE ON SHIFT_HANDOVER(ShiftDate);
