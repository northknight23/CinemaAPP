-- Chạy trên CINEMADB trước khi sử dụng POS thật. Không xóa dữ liệu cũ.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF COL_LENGTH('dbo.ACCOUNT', 'IsActive') IS NULL
    EXEC(N'ALTER TABLE dbo.ACCOUNT ADD IsActive BIT NOT NULL CONSTRAINT DF_POS_ACCOUNT_ACTIVE DEFAULT 1 WITH VALUES');
IF COL_LENGTH('dbo.SEAT', 'SeatType') IS NULL
    EXEC(N'ALTER TABLE dbo.SEAT ADD SeatType NVARCHAR(10) NOT NULL CONSTRAINT DF_POS_SEAT_TYPE DEFAULT N''Standard'' WITH VALUES');
IF COL_LENGTH('dbo.BOOKING', 'PaymentMethod') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD PaymentMethod NVARCHAR(20) NULL');
IF COL_LENGTH('dbo.BOOKING', 'CashGiven') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CashGiven MONEY NULL');
IF COL_LENGTH('dbo.BOOKING', 'PointsEarned') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD PointsEarned INT NOT NULL CONSTRAINT DF_POS_POINTS_EARNED DEFAULT 0 WITH VALUES');
IF COL_LENGTH('dbo.BOOKING', 'PointsUsed') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD PointsUsed INT NOT NULL CONSTRAINT DF_POS_POINTS_USED DEFAULT 0 WITH VALUES');
IF COL_LENGTH('dbo.BOOKING', 'CancelReason') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CancelReason NVARCHAR(200) NULL');
IF COL_LENGTH('dbo.BOOKING', 'CancelledAt') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CancelledAt DATETIME2 NULL');
IF COL_LENGTH('dbo.BOOKING', 'CancelledBy') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CancelledBy INT NULL REFERENCES dbo.ACCOUNT(AccountID)');
IF COL_LENGTH('dbo.TICKET', 'TicketStatus') IS NULL
BEGIN
    EXEC(N'ALTER TABLE dbo.TICKET ADD TicketStatus NVARCHAR(20) NOT NULL CONSTRAINT DF_POS_TICKET_STATUS DEFAULT N''Active'' WITH VALUES');
    EXEC(N'UPDATE t SET TicketStatus=N''Cancelled'' FROM dbo.TICKET t JOIN dbo.BOOKING b ON b.BookingID=t.BookingID WHERE b.BookingStatus=N''Cancelled''');
END;
IF COL_LENGTH('dbo.TICKET', 'RoomID') IS NULL
BEGIN
    EXEC(N'ALTER TABLE dbo.TICKET ADD RoomID INT NULL');
    EXEC(N'UPDATE t SET RoomID=s.RoomID FROM dbo.TICKET t JOIN dbo.SEAT s ON s.SeatID=t.SeatID');
    EXEC(N'ALTER TABLE dbo.TICKET ALTER COLUMN RoomID INT NOT NULL');
END;
IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE parent_object_id=OBJECT_ID('dbo.TICKET') AND name='UQ_TICKET_SEAT')
    ALTER TABLE dbo.TICKET DROP CONSTRAINT UQ_TICKET_SEAT;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.TICKET') AND name='UQ_TICKET_SEAT')
    EXEC(N'CREATE UNIQUE INDEX UQ_TICKET_SEAT ON dbo.TICKET(ShowtimeID,SeatID) WHERE TicketStatus=N''Active''');
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.BOOKING') AND name='IX_POS_BOOKING_CUSTOMER')
    CREATE INDEX IX_POS_BOOKING_CUSTOMER ON dbo.BOOKING(CustomerID);
COMMIT;
