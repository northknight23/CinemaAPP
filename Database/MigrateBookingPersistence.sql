-- Chạy trên CINEMADB trước khi sử dụng POS thật. Không xóa dữ liệu cũ.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF COL_LENGTH('dbo.ACCOUNT', 'IsActive') IS NULL
    EXEC(N'ALTER TABLE dbo.ACCOUNT ADD IsActive BIT NOT NULL CONSTRAINT DF_POS_ACCOUNT_ACTIVE DEFAULT 1 WITH VALUES');
IF COL_LENGTH('dbo.SEAT', 'SeatType') IS NULL
    EXEC(N'ALTER TABLE dbo.SEAT ADD SeatType NVARCHAR(10) NOT NULL CONSTRAINT DF_POS_SEAT_TYPE DEFAULT N''Standard'' WITH VALUES');
IF COL_LENGTH('dbo.BOOKING', 'PaymentMethod') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD PaymentMethod NVARCHAR(20) NULL');
IF COL_LENGTH('dbo.BOOKING', 'CashGiven') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CashGiven MONEY NULL');
IF COL_LENGTH('dbo.BOOKING', 'PointsEarned') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD PointsEarned INT NOT NULL CONSTRAINT DF_POS_POINTS_EARNED DEFAULT 0 WITH VALUES');
IF COL_LENGTH('dbo.BOOKING', 'PointsUsed') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD PointsUsed INT NOT NULL CONSTRAINT DF_POS_POINTS_USED DEFAULT 0 WITH VALUES');
IF COL_LENGTH('dbo.BOOKING', 'CancelReason') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CancelReason NVARCHAR(200) NULL');
IF COL_LENGTH('dbo.BOOKING', 'CancelledAt') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CancelledAt DATETIME2 NULL');
IF COL_LENGTH('dbo.BOOKING', 'CancelledBy') IS NULL
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CancelledBy INT NULL REFERENCES dbo.ACCOUNT(AccountID)');
IF COL_LENGTH('dbo.TICKET', 'TicketStatus') IS NULL
BEGIN
    EXEC(N'ALTER TABLE dbo.TICKET ADD TicketStatus NVARCHAR(20) NOT NULL CONSTRAINT DF_POS_TICKET_STATUS DEFAULT N''Active'' WITH VALUES');
    EXEC(N'UPDATE t SET TicketStatus=N''Cancelled'' FROM dbo.TICKET t JOIN dbo.BOOKING b ON b.BookingID=t.BookingID WHERE b.BookingStatus=N''Cancelled''');
END;
IF COL_LENGTH('dbo.TICKET', 'RoomID') IS NULL
BEGIN
    EXEC(N'ALTER TABLE dbo.TICKET ADD RoomID INT NULL');
    EXEC(N'UPDATE t SET RoomID=s.RoomID FROM dbo.TICKET t JOIN dbo.SEAT s ON s.SeatID=t.SeatID');
    EXEC(N'ALTER TABLE dbo.TICKET ALTER COLUMN RoomID INT NOT NULL');
END;
IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE parent_object_id=OBJECT_ID('dbo.TICKET') AND name='UQ_TICKET_SEAT')
    ALTER TABLE dbo.TICKET DROP CONSTRAINT UQ_TICKET_SEAT;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.TICKET') AND name='UQ_TICKET_SEAT')
    EXEC(N'CREATE UNIQUE INDEX UQ_TICKET_SEAT ON dbo.TICKET(ShowtimeID,SeatID) WHERE TicketStatus=N''Active''');
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.BOOKING') AND name='IX_POS_BOOKING_CUSTOMER')
    CREATE INDEX IX_POS_BOOKING_CUSTOMER ON dbo.BOOKING(CustomerID);
IF OBJECT_ID('dbo.SHIFT_HANDOVER', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.SHIFT_HANDOVER (
        ShiftHandoverID INT IDENTITY(1,1) PRIMARY KEY,
        ShiftDate       DATE NOT NULL,
        AccountID       INT NOT NULL,
        ReportedCash    MONEY NULL,
        ReportNote      NVARCHAR(300) NULL,
        ReportedAt      DATETIME2 NULL,
        ConfirmedCash   MONEY NULL,
        ConfirmNote     NVARCHAR(300) NULL,
        ConfirmedAt     DATETIME2 NULL,
        ConfirmedBy     INT NULL,
        CONSTRAINT UQ_SHIFT_HANDOVER_DATE_ACCOUNT UNIQUE (ShiftDate, AccountID),
        CONSTRAINT FK_SHIFT_HANDOVER_ACCOUNT FOREIGN KEY (AccountID) REFERENCES dbo.ACCOUNT(AccountID),
        CONSTRAINT FK_SHIFT_HANDOVER_CONFIRMEDBY FOREIGN KEY (ConfirmedBy) REFERENCES dbo.ACCOUNT(AccountID),
        CONSTRAINT CK_SHIFT_HANDOVER_REPORTED_CASH CHECK (ReportedCash IS NULL OR ReportedCash >= 0),
        CONSTRAINT CK_SHIFT_HANDOVER_CONFIRMED_CASH CHECK (ConfirmedCash IS NULL OR ConfirmedCash >= 0),
        CONSTRAINT CK_SHIFT_HANDOVER_STATE CHECK (ReportedAt IS NOT NULL OR ConfirmedAt IS NOT NULL),
        CONSTRAINT CK_SHIFT_HANDOVER_REPORT_PAIR CHECK ((ReportedAt IS NULL AND ReportedCash IS NULL) OR (ReportedAt IS NOT NULL AND ReportedCash IS NOT NULL)),
        CONSTRAINT CK_SHIFT_HANDOVER_CONFIRM_PAIR CHECK ((ConfirmedAt IS NULL AND ConfirmedCash IS NULL AND ConfirmedBy IS NULL) OR (ConfirmedAt IS NOT NULL AND ConfirmedCash IS NOT NULL AND ConfirmedBy IS NOT NULL))
    );
    CREATE INDEX IX_SHIFT_HANDOVER_DATE ON dbo.SHIFT_HANDOVER(ShiftDate);
END;
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.ROOM') AND name='CK_ROOM_TYPE')
    EXEC(N'ALTER TABLE dbo.ROOM ADD CONSTRAINT CK_ROOM_TYPE CHECK(RoomType IN (N''2D'', N''3D'', N''IMAX''))');
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.BOOKING') AND name='CK_BOOKING_GUEST_POINTS')
    EXEC(N'ALTER TABLE dbo.BOOKING ADD CONSTRAINT CK_BOOKING_GUEST_POINTS CHECK(CustomerID IS NOT NULL OR (PointsEarned = 0 AND PointsUsed = 0))');
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.SHIFT_HANDOVER') AND name='CK_SHIFT_HANDOVER_REPORT_PAIR')
    EXEC(N'ALTER TABLE dbo.SHIFT_HANDOVER ADD CONSTRAINT CK_SHIFT_HANDOVER_REPORT_PAIR CHECK((ReportedAt IS NULL AND ReportedCash IS NULL) OR (ReportedAt IS NOT NULL AND ReportedCash IS NOT NULL))');
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.SHIFT_HANDOVER') AND name='CK_SHIFT_HANDOVER_CONFIRM_PAIR')
    EXEC(N'ALTER TABLE dbo.SHIFT_HANDOVER ADD CONSTRAINT CK_SHIFT_HANDOVER_CONFIRM_PAIR CHECK((ConfirmedAt IS NULL AND ConfirmedCash IS NULL AND ConfirmedBy IS NULL) OR (ConfirmedAt IS NOT NULL AND ConfirmedCash IS NOT NULL AND ConfirmedBy IS NOT NULL))');
COMMIT;
